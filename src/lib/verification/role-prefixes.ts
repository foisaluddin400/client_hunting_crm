export function isRoleBasedEmail(localPart: string): boolean {
  if (!localPart) return false;
  const clean = localPart.toLowerCase().trim().replace(/[\+\.0-9_-].*$/, "");
  if (ROLE_PREFIXES.has(clean)) return true;
  return ROLE_PREFIXES.has(localPart.toLowerCase().trim());
}
